    // Live updates: a small companion mod inside BeamNG polls a request file in the user folder.
    // It lives inside the AutoBeam pack (see AutoBeamPack). After an install it tells BeamNG which pack
    // files changed and reloads (or refits) the car the player is driving. For old separate engine zips
    // it can still unmount one (BeamNG keeps mounted zips locked) so it can be deleted.
    static class LiveLink
    {
        public const string Version = "5";
        public const string ModZip = "automationToBeamNG_liveReload.zip";
        const string ExtName = "automationToBeamNG_live";

        // userfolder/automationToBeamNG/ is "/automationToBeamNG/" inside BeamNG
        static string Dir(string mods) { return Path.Combine(Path.GetDirectoryName(mods.TrimEnd('\\', '/')), "automationToBeamNG"); }

        public const string ModScript =
@"-- Generated by AutomationToBeamNG: loads the live-update link.
setExtensionUnloadMode(""automationToBeamNG_live"", ""manual"")
extensions.load(""automationToBeamNG_live"")
";

        public const string Lua =
@"-- Generated by AutomationToBeamNG. Lets the converter app swap its engine mods and reload your car
-- while the game is running. It only reads /automationToBeamNG/request.json and only touches mods
-- whose names start with ""automation_"".
-- Debugging (actions ""ge"" and ""vlua"", which run Lua in the game or in your car) only works while
-- /automationToBeamNG/debug.on exists; delete that file to switch it off.
local M = {}

local version = ""5""
local dir = ""/automationToBeamNG/""
local lastId = nil
local lastDebugId = nil
local timer = 0
local pending = nil
-- two channels so debugging never overwrites an install's requests: request/response.json for the
-- converter, debug_request/debug_response.json for debugging tools. Each request id says where to answer.
local channelOf = {}

local function respond(id, ok, msg, extra)
  local r = extra or {}
  r.id = id
  r.ok = ok
  r.msg = msg
  r.version = version
  jsonWriteFile(dir .. (channelOf[id] or ""response.json""), r, false, nil, true)
end

local function ourMod(name)
  return type(name) == ""string"" and name:sub(1, 11) == ""automation_""
end

local function playerModel()
  local veh = be:getPlayerVehicle(0)
  return veh and veh:getJBeamFilename() or nil
end

-- swaps whichever part sits in the engine slot for ours; the sub-parts go back to our engine's defaults
local function fitEngine(veh, partName, slotType)
  local vd = core_vehicle_manager.getVehicleData(veh:getId())
  if not vd or not vd.config or not vd.config.partsTree or not vd.ioCtx then return false end
  local jbeamIO = require(""jbeam/io"")
  local function fits(name)
    if type(name) ~= ""string"" or name == """" then return false end
    local p = jbeamIO.getPart(vd.ioCtx, name)
    if not p then return false end
    if type(p.slotType) == ""table"" then
      for _, s in ipairs(p.slotType) do if s == slotType then return true end end
      return false
    end
    return p.slotType == slotType
  end
  local function walk(node)
    if fits(node.chosenPartName) then
      node.chosenPartName = partName
      node.children = {}
      return true
    end
    for _, c in pairs(node.children or {}) do
      if type(c) == ""table"" and walk(c) then return true end
    end
    return false
  end
  if not walk(vd.config.partsTree) then return false end
  core_vehicle_partmgmt.setConfigOfVehicle(veh, {}, true)
  return true
end

-- every spawned car keeps the list of parts that fit each slot from when it spawned; rebuild those lists
-- so a newly installed engine shows up in the other cars too, not only the one that gets reloaded
local function refreshPartLists()
  local jbeamIO = require(""jbeam/io"")
  local function update(ioCtx, node, slotMap)
    local part = jbeamIO.getPart(ioCtx, node.chosenPartName)
    local slots = part and (part.slots2 or part.slots)
    if not slots or type(node.children) ~= ""table"" then return end
    for _, slotDef in ipairs(slots) do
      local child = node.children[slotDef.name or slotDef.type]
      if type(child) == ""table"" then
        child.suitablePartNames, child.unsuitablePartNames = jbeamIO.getCompatiblePartNamesForSlot(ioCtx, slotDef, slotMap)
        update(ioCtx, child, slotMap)
      end
    end
  end
  for i = 0, be:getObjectCount() - 1 do
    local v = be:getObject(i)
    local vd = v and core_vehicle_manager.getVehicleData(v:getId())
    if vd and vd.ioCtx and vd.ioCtx.preloadedDirs and vd.config and vd.config.partsTree then
      local ok, err = pcall(function()
        jbeamIO.startLoading(vd.ioCtx.preloadedDirs)
        local slotMap = jbeamIO.getAvailableSlotNameMap(vd.ioCtx)
        if slotMap then update(vd.ioCtx, vd.config.partsTree, slotMap) end
      end)
      if not ok then log(""W"", ""automationToBeamNG"", ""couldn't refresh the parts list: "" .. tostring(err)) end
    end
  end
end

local function finishReload(req)
  pcall(refreshPartLists)
  local veh = be:getPlayerVehicle(0)
  local model = veh and veh:getJBeamFilename() or nil
  local car = model and type(req.cars) == ""table"" and req.cars[model] or nil
  if not car then
    respond(req.id, true, ""mods reloaded"", { player = model })
    return
  end
  if req.fit and type(car) == ""table"" and car.part and car.slotType then
    local ok, fitted = pcall(fitEngine, veh, car.part, car.slotType)
    if ok and fitted then
      respond(req.id, true, ""engine fitted"", { player = model, fitted = true })
      return
    end
    log(""W"", ""automationToBeamNG"", ""couldn't fit the engine: "" .. tostring(fitted))
  end
  core_vehicle_manager.reloadVehicle(0)
  respond(req.id, true, ""vehicle reloaded"", { player = model, reloaded = true })
end

-- results must survive jsonWriteFile: tables recursively, numbers/strings/booleans as they are,
-- everything else (functions, userdata, cdata) as text; cycles and depth are cut off
local function plain(x, depth, seen)
  local t = type(x)
  if t == ""number"" then return (x ~= x or x == math.huge or x == -math.huge) and tostring(x) or x end
  if t == ""string"" or t == ""boolean"" or t == ""nil"" then return x end
  if t ~= ""table"" then return tostring(x) end
  depth = depth or 0
  seen = seen or {}
  if seen[x] or depth > 6 then return ""<table>"" end
  seen[x] = true
  local r, n = {}, 0
  for k, val in pairs(x) do
    n = n + 1
    if n > 2000 then r[""...""] = ""(cut)"" break end
    r[tostring(k)] = plain(val, depth + 1, seen)
  end
  seen[x] = nil
  return r
end

local function debugOn() return FS:fileExists(dir .. ""debug.on"") end

-- vehicle-side results come back through here (see the ""vlua"" action) as a serialized {ok, res}
local function vluaResult(id, s)
  local okd, t = pcall(deserialize, s)
  if not okd or type(t) ~= ""table"" then respond(id, false, ""unreadable result from the car"") return end
  respond(id, t.ok and true or false, t.ok and ""ok"" or tostring(t.res), { result = plain(t.res) })
end

-- what runs inside the car for ""vlua"": the code, then its result sent back to vluaResult
local vehicleWrapper = [[
local f, err = load(code, 'a2b_vdebug', 't')
local ok, res
if f then ok, res = pcall(f) else ok, res = false, 'compile: ' .. tostring(err) end
local sok, s = pcall(serialize, { ok = ok, res = res })
if not sok then s = serialize({ ok = ok, res = tostring(res) }) end
obj:queueGameEngineLua('automationToBeamNG_live.vluaResult(' .. string.format('%q', id) .. ', ' .. string.format('%q', s) .. ')')
]]

local function handle(req)
  if req.action == ""hello"" then
    respond(req.id, true, ""hello"", { player = playerModel(), debug = debugOn() })

  elseif req.action == ""ge"" or req.action == ""vlua"" then
    if not debugOn() then respond(req.id, false, ""debugging is off (no /automationToBeamNG/debug.on)"") return end
    if type(req.code) ~= ""string"" then respond(req.id, false, ""no code"") return end
    if req.action == ""ge"" then
      local f, err = load(req.code, ""a2b_debug"", ""t"")
      if not f then respond(req.id, false, ""compile: "" .. tostring(err)) return end
      local ok, res = pcall(f)
      respond(req.id, ok, ok and ""ok"" or tostring(res), { result = plain(res) })
    else
      local veh = be:getPlayerVehicle(0)
      if not veh then respond(req.id, false, ""no player vehicle"") return end
      veh:queueLuaCommand(""local code = "" .. string.format(""%q"", req.code) .. ""\nlocal id = "" .. string.format(""%q"", req.id) .. ""\n"" .. vehicleWrapper)
    end

  elseif req.action == ""unmount"" then
    local mods = core_modmanager.getMods() or {}
    local done = {}
    for _, name in ipairs(req.mods or {}) do
      local m = ourMod(name) and mods[name] or nil
      if m and m.fullpath and FS:isMounted(m.fullpath) then
        FS:unmount(m.fullpath)
        table.insert(done, name)
      end
    end
    respond(req.id, true, ""unmounted"", { unmounted = done })

  elseif req.action == ""reload"" then
    -- the AutoBeam pack is a folder: forget the cached copies of the jbeam files that changed
    local jbeamIO = require(""jbeam/io"")
    for _, f in ipairs(req.files or {}) do
      if type(f) == ""string"" and f:sub(-6) == "".jbeam"" then pcall(jbeamIO.onFileChanged, ""/"" .. f, ""modified"") end
    end
    for _, name in ipairs(req.mods or {}) do
      if ourMod(name) then
        local ok, err = pcall(core_modmanager.workOffChangedMod, ""/mods/"" .. name .. "".zip"", ""modified"")
        if not ok then log(""E"", ""automationToBeamNG"", ""remount failed: "" .. tostring(err)) end
        local m = (core_modmanager.getMods() or {})[name]
        if m and m.fullpath and not FS:isMounted(m.fullpath) then pcall(core_modmanager.activateMod, name) end
      end
    end
    -- give the file-change notifications a moment to clear BeamNG's jbeam caches
    pending = { at = 0.75, req = req }

  else
    respond(req.id, false, ""unknown action "" .. tostring(req.action))
  end
end

local function onUpdate(dtReal)
  dtReal = dtReal or 0
  if pending then
    pending.at = pending.at - dtReal
    if pending.at <= 0 then
      local req = pending.req
      pending = nil
      local ok, err = pcall(finishReload, req)
      if not ok then respond(req.id, false, tostring(err)) end
    end
  end
  timer = timer + dtReal
  if timer < 0.25 then return end
  timer = 0
  local req = jsonReadFile(dir .. ""request.json"")
  if type(req) == ""table"" and req.id and req.id ~= lastId then
    lastId = req.id
    channelOf[req.id] = ""response.json""
    local ok, err = pcall(handle, req)
    if not ok then respond(req.id, false, tostring(err)) end
  end
  local dreq = jsonReadFile(dir .. ""debug_request.json"")
  if type(dreq) == ""table"" and dreq.id and dreq.id ~= lastDebugId then
    lastDebugId = dreq.id
    channelOf[dreq.id] = ""debug_response.json""
    local ok, err = pcall(handle, dreq)
    if not ok then respond(dreq.id, false, tostring(err)) end
  end
end

local function onExtensionLoaded()
  -- don't replay requests left over from before the game started
  local req = jsonReadFile(dir .. ""request.json"")
  if type(req) == ""table"" then lastId = req.id end
  local dreq = jsonReadFile(dir .. ""debug_request.json"")
  if type(dreq) == ""table"" then lastDebugId = dreq.id end
  log(""I"", ""automationToBeamNG"", ""live update link ready"")
end

M.onUpdate = onUpdate
M.onExtensionLoaded = onExtensionLoaded
M.vluaResult = vluaResult
return M
";

        // Writes the link into the AutoBeam pack when it's missing or older. Returns false while BeamNG has an
        // older one loaded: replacing a running extension's files is only done while the game is closed.
        public static bool EnsureInstalled(string mods)
        {
            string pack = AutoBeamPack.Dir(mods);
            string verFile = Path.Combine(pack, "automation_to_beamng_live", "version.txt");
            string have = null;
            try { if (File.Exists(verFile)) have = File.ReadAllText(verFile).Trim(); } catch (Exception) { }
            if (have == Version) return true;
            if (have != null && BeamNGProcess.IsRunning()) return false;
            try
            {
                Action<string, string> add = (name, text) =>
                {
                    string p = Path.Combine(pack, name.Replace('/', Path.DirectorySeparatorChar));
                    Directory.CreateDirectory(Path.GetDirectoryName(p));
                    File.WriteAllText(p, text.Replace("\r\n", "\n"), new UTF8Encoding(false));
                };
                add("lua/ge/extensions/automationToBeamNG/live.lua", Lua);
                add("scripts/" + ExtName + "/modScript.lua", ModScript);
                add("automation_to_beamng_live/version.txt", Version);
                return true;
            }
            catch (IOException) { return false; }
            catch (UnauthorizedAccessException) { return false; }
        }

        public static bool Installed(string mods) { return File.Exists(Path.Combine(AutoBeamPack.Dir(mods), "automation_to_beamng_live", "version.txt")); }
        // One request/response round trip; null when BeamNG didn't answer in time.
        // debug: use the debugging channel (debug_request/debug_response.json), so debugging tools never
        // overwrite a request the converter is waiting on
        public static Dictionary<string, object> Ask(string mods, Dictionary<string, object> req, int timeoutMs, bool debug = false)
        {
            string dir = Dir(mods);
            Directory.CreateDirectory(dir);
            string id = DateTime.UtcNow.Ticks.ToString(Num.Inv) + "-" + Process.GetCurrentProcess().Id;
            req["id"] = id;
            string reqPath = Path.Combine(dir, debug ? "debug_request.json" : "request.json"), respPath = Path.Combine(dir, debug ? "debug_response.json" : "response.json");
            var js = new JavaScriptSerializer();
            string tmp = reqPath + ".tmp";
            File.WriteAllText(tmp, js.Serialize(req), new UTF8Encoding(false));
            if (File.Exists(reqPath)) File.Delete(reqPath);
            File.Move(tmp, reqPath);
            var sw = Stopwatch.StartNew();
            while (sw.ElapsedMilliseconds < timeoutMs)
            {
                Thread.Sleep(100);
                try
                {
                    if (!File.Exists(respPath)) continue;
                    var r = js.DeserializeObject(File.ReadAllText(respPath)) as Dictionary<string, object>;
                    object rid;
                    if (r != null && r.TryGetValue("id", out rid) && (rid as string) == id) return r;
                }
                catch (Exception) { }   // half-written; try again
            }
            return null;
        }

        public static bool IsConnected(string mods)
        {
            if (!BeamNGProcess.IsRunning()) return false;
            // only the link inside the pack (this version) can update the pack live
            var r = Ask(mods, new Dictionary<string, object> { { "action", "hello" } }, 1500);
            object v;
            return r != null && r.TryGetValue("version", out v) && (v as string) == Version;
        }

        // Called by the converter when the engine zip it wants to replace is locked: asks BeamNG to let go of it.
        public static bool Unmount(string mods, string zipPath)
        {
            var r = Ask(mods, new Dictionary<string, object> { { "action", "unmount" }, { "mods", new[] { ModName(zipPath) } } }, 3000);
            return r != null && true.Equals(r["ok"]);
        }

        // After the install: BeamNG re-reads the changed pack files (and remounts zipPath, an old separate
        // engine zip, if given), then reloads (or refits) the player's car. Returns a line for the user.
        public static string Reload(string mods, string zipPath, List<string> changed, Dictionary<string, string[]> cars, bool fit, Func<string, string> carName)
        {
            var carObj = cars.ToDictionary(kv => kv.Key, kv => (object)new Dictionary<string, object> { { "part", kv.Value[0] }, { "slotType", kv.Value[1] } });
            var r = Ask(mods, new Dictionary<string, object> { { "action", "reload" }, { "mods", zipPath != null ? new[] { ModName(zipPath) } : new string[0] },
                                                              { "files", (changed ?? new List<string>()).ToArray() }, { "cars", carObj }, { "fit", fit } }, 8000);
            if (r == null) return "BeamNG didn't answer, so restart it (or press Ctrl+R in your car) to see the engine.";
            object o;
            if (!true.Equals(r["ok"])) return "BeamNG couldn't reload the engine (" + (r.TryGetValue("msg", out o) ? o : "") + "). Press Ctrl+R in your car.";
            string player = r.TryGetValue("player", out o) ? o as string : null;
            string car = player != null ? carName(player) : null;
            if (r.ContainsKey("fitted")) return "BeamNG fitted the engine to your " + car + ".";
            if (r.ContainsKey("reloaded")) return "BeamNG reloaded your " + car + " with the new version.";
            return "BeamNG loaded the engine. Pick it in the parts menu (or spawn its config) to try it.";
        }

        static string ModName(string zipPath) { return Path.GetFileNameWithoutExtension(zipPath).ToLowerInvariant(); }

        // ---- debugging: run Lua in the game ("ge") or inside the player's car ("vlua") and get the
        // result back (response keys: ok, msg, result). Only works while debugging is switched on.
        public static Dictionary<string, object> Run(string mods, string where, string code, int timeoutMs)
        {
            if (where != "ge" && where != "vlua") throw new ArgumentException("where must be \"ge\" or \"vlua\"");
            return Ask(mods, new Dictionary<string, object> { { "action", where }, { "code", code } }, timeoutMs, true);
        }

        // hello on the debugging channel (for debugging tools; the converter uses IsConnected)
        public static Dictionary<string, object> Hello(string mods, int timeoutMs)
        {
            return Ask(mods, new Dictionary<string, object> { { "action", "hello" } }, timeoutMs, true);
        }

        public static bool DebugEnabled(string mods) { return File.Exists(Path.Combine(Dir(mods), "debug.on")); }

        public static void SetDebug(string mods, bool on)
        {
            string f = Path.Combine(Dir(mods), "debug.on");
            if (on) { Directory.CreateDirectory(Dir(mods)); File.WriteAllText(f, "Lets the AutomationToBeamNG converter (and debugging tools) run Lua in BeamNG. Delete this file to switch it off.\r\n"); }
            else if (File.Exists(f)) File.Delete(f);
        }
    }
